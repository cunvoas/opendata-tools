  ON adm_com2commune (siren)
  WHERE siren IS NOT NULL;

-- Un SIREN mal formé doit faire échouer la migration, pas entrer silencieusement en base.
DO $$
DECLARE invalides integer;
BEGIN
  SELECT count(*) INTO invalides
  FROM adm_com2commune
  WHERE siren IS NOT NULL AND siren !~ '^[0-9]{9}$';

  IF invalides > 0 THEN
    RAISE EXCEPTION 'SIREN invalide sur % EPCI, migration annulée', invalides;
  END IF;
END $$;
